export const FONT_W = 5;
export const FONT_H = 7;
export const FONT_ADVANCE = 6;

/** true if glyph `ch` has a pixel at column x, row y (row 0 = top). */
export function glyphPixel(ch: string, x: number, y: number): boolean {
  const g = GLYPHS[ch] ?? GLYPHS['?'];
  return g[y][x] === '#';
}

export function textWidth(s: string, scale = 1): number {
  return s.length === 0 ? 0 : (s.length * FONT_ADVANCE - 1) * scale;
}
